const API_ERRORS: Record<string, MessageKey> = {
  "invalid credentials": "errInvalidCredentials",
  "name and password required": "errNamePassword",
  "password required": "errPassword",
  "name required": "errName",
  "too many attempts": "errTooMany",
  "sync failed": "errSyncFailed",
  failed: "errFailed",
  "not found": "errNotFound",
  unauthorized: "errUnauthorized",
};

export function translateError(message: string, t: (key: MessageKey) => string): string {
  const key = API_ERRORS[message];
  return key ? t(key) : message;
}

export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}
